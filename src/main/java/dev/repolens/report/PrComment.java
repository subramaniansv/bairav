package dev.repolens.report;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import dev.repolens.model.Finding;
import dev.repolens.model.ProjectResult;
import dev.repolens.model.Severity;

import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.time.Duration;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Pull-request bot mode: renders a short Markdown summary (new findings only when a baseline exists),
 * writes inline-review JSON, and optionally posts/updates one comment on a GitHub PR.
 * Never includes secret values: it only uses finding messages, which are already scrubbed.
 */
public final class PrComment {

    public static final String MARKER = "<!-- bairav-pr-comment -->";
    private static final int MAX_ROWS = 15;
    private static final int MAX_INLINE = 20;
    private static final Pattern REPO = Pattern.compile("[\\w.-]+/[\\w.-]+");
    private static final ObjectMapper JSON = new ObjectMapper();

    public record Target(String repo, int number) {}

    public record Inline(String path, int line, String side, String body) {}

    private PrComment() {}

    /** "owner/repo#12", or "auto" in GitHub Actions (GITHUB_REPOSITORY + GITHUB_REF=refs/pull/12/merge). */
    public static Target parseTarget(String spec, Map<String, String> env) {
        if (spec == null) return null;
        String repo;
        String num;
        if (spec.equals("auto")) {
            repo = env.get("GITHUB_REPOSITORY");
            Matcher m = Pattern.compile("refs/pull/(\\d+)/").matcher(env.getOrDefault("GITHUB_REF", ""));
            num = m.find() ? m.group(1) : null;
        } else {
            int i = spec.lastIndexOf('#');
            if (i < 0) throw new IllegalArgumentException("Expected owner/repo#number or 'auto', got: " + spec);
            repo = spec.substring(0, i);
            num = spec.substring(i + 1);
        }
        if (repo == null || num == null) return null; // not running on a pull request
        if (!REPO.matcher(repo).matches() || !num.matches("\\d{1,9}")) {
            throw new IllegalArgumentException("Invalid pull request target: " + spec);
        }
        return new Target(repo, Integer.parseInt(num));
    }

    public static String render(List<ProjectResult> projects, Baseline.Diff diff, Gate gate) {
        List<Finding> shown = diff != null ? new ArrayList<>(diff.added()) : new ArrayList<>();
        if (diff == null) {
            projects.forEach(p -> p.findings().stream().filter(f -> f.severity().weight >= Severity.HIGH.weight).forEach(shown::add));
        }
        shown.sort(Comparator.comparingInt((Finding f) -> -f.severity().weight).thenComparing(Finding::file));

        StringBuilder m = new StringBuilder(MARKER).append('\n');
        m.append("## Bairav: ").append(gate.passed() ? "✅ quality gate passed" : "❌ quality gate failed").append("\n\n");
        if (!gate.passed()) gate.violations().forEach(v -> m.append("- ").append(v).append('\n'));
        m.append("\n| Project | Grade | Score |\n|---|---|---|\n");
        projects.forEach(p -> m.append("| ").append(p.name()).append(" | ").append(p.scores().grade()).append(" | ")
                .append(p.scores().overall()).append(" |\n"));

        Map<Severity, Long> counts = new LinkedHashMap<>();
        for (Severity s : List.of(Severity.CRITICAL, Severity.HIGH, Severity.MEDIUM, Severity.LOW)) {
            counts.put(s, shown.stream().filter(f -> f.severity() == s).count());
        }
        m.append('\n').append(diff != null ? "**New findings in this PR: " : "**High-severity findings: ").append(shown.size()).append("**");
        if (diff != null) m.append(" (").append(diff.fixed()).append(" fixed)");
        m.append("  \n");
        counts.forEach((s, c) -> { if (c > 0) m.append(emoji(s)).append(' ').append(c).append(' ').append(s).append("  "); });
        m.append("\n\n");
        if (shown.isEmpty()) {
            m.append("No ").append(diff != null ? "new" : "high-severity").append(" findings. 🎉\n");
        } else {
            m.append("| Severity | Location | Issue |\n|---|---|---|\n");
            shown.stream().limit(MAX_ROWS).forEach(f -> m.append("| ").append(emoji(f.severity())).append(' ').append(f.severity())
                    .append(" | `").append(f.file()).append(f.line() > 0 ? ":" + f.line() : "").append("` | ")
                    .append(escape(f.message())).append(" |\n"));
            if (shown.size() > MAX_ROWS) m.append("\n…and ").append(shown.size() - MAX_ROWS).append(" more in the full report.\n");
        }
        m.append("\n<sub>Generated by Bairav. Full detail in the `bairav-report` artifact (report.html, ai-fix-plan.md).</sub>\n");
        return m.toString();
    }

    public static List<Inline> inline(List<ProjectResult> projects, Baseline.Diff diff) {
        List<Finding> src = diff != null ? diff.added()
                : projects.stream().flatMap(p -> p.findings().stream()).toList();
        List<Inline> out = new ArrayList<>();
        src.stream().filter(f -> f.line() > 0 && f.severity().weight >= Severity.MEDIUM.weight && !f.file().startsWith("http"))
                .sorted(Comparator.comparingInt((Finding f) -> -f.severity().weight))
                .limit(MAX_INLINE)
                .forEach(f -> out.add(new Inline(f.file(), f.line(), "RIGHT",
                        emoji(f.severity()) + " **" + f.severity() + "**: " + f.message()
                                + (f.fix() == null ? "" : "\n\n_Fix:_ " + f.fix()))));
        return out;
    }

    /** Creates the Bairav comment, or edits the previous one so a PR never collects a pile of comments. */
    public static void post(Target t, String body, List<Inline> inline, String token, String apiBase) throws IOException, InterruptedException {
        HttpClient http = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(15)).build();
        String base = apiBase.replaceAll("/+$", "") + "/repos/" + t.repo();

        JsonNode existing = JSON.readTree(send(http, token, "GET", base + "/issues/" + t.number() + "/comments?per_page=100", null).body());
        Long id = null;
        for (JsonNode c : existing) if (c.path("body").asText().contains(MARKER)) id = c.path("id").asLong();
        String payload = JSON.writeValueAsString(Map.of("body", body));
        HttpResponse<String> r = id == null
                ? send(http, token, "POST", base + "/issues/" + t.number() + "/comments", payload)
                : send(http, token, "PATCH", base + "/issues/comments/" + id, payload);
        if (r.statusCode() / 100 != 2) throw new IOException("GitHub returned HTTP " + r.statusCode() + " when posting the comment");

        if (inline != null && !inline.isEmpty()) {
            Map<String, Object> review = new LinkedHashMap<>();
            review.put("body", "Bairav inline findings (new in this PR)");
            review.put("event", "COMMENT");
            review.put("comments", inline);
            HttpResponse<String> rr = send(http, token, "POST", base + "/pulls/" + t.number() + "/reviews", JSON.writeValueAsString(review));
            if (rr.statusCode() / 100 != 2) {
                System.out.println("Inline review not posted (HTTP " + rr.statusCode() + "; usually a finding is outside the PR diff). Summary comment was posted.");
            }
        }
    }

    private static HttpResponse<String> send(HttpClient http, String token, String method, String url, String body)
            throws IOException, InterruptedException {
        HttpRequest.Builder b = HttpRequest.newBuilder(URI.create(url)).timeout(Duration.ofSeconds(30))
                .header("Accept", "application/vnd.github+json").header("Authorization", "Bearer " + token)
                .header("X-GitHub-Api-Version", "2022-11-28").header("User-Agent", "bairav");
        if (body != null) b.header("Content-Type", "application/json").method(method, HttpRequest.BodyPublishers.ofString(body));
        else b.method(method, HttpRequest.BodyPublishers.noBody());
        return http.send(b.build(), HttpResponse.BodyHandlers.ofString());
    }

    private static String emoji(Severity s) {
        return switch (s) {
            case CRITICAL -> "🔴";
            case HIGH -> "🟠";
            case MEDIUM -> "🟡";
            default -> "⚪";
        };
    }

    private static String escape(String s) {
        return s.replace("|", "\\|").replace("\n", " ");
    }
}
